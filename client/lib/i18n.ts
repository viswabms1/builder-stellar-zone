export function getLanguageLabel(lang: Language): string {
  switch (lang) {
    case 'en':
      return 'English';
    case 'kn':
      return 'ಕನ್ನಡ';
    case 'hi':
      return 'हिंदी';
    default:
      return 'English';
  }
}

export function getTranslation(lang: Language, key: string): string {
  const keys = key.split('.');
  let value: any = translations[lang];

  for (const k of keys) {
    value = value?.[k];
  }

  // Fallback to English if translation not found
  if (!value) {
    let enValue: any = translations.en;
    for (const k of keys) {
      enValue = enValue?.[k];
    }
    return enValue || key;
  }

  return value || key;
}

// Extended translation function supporting nested keys
export function t(lang: Language, key: string): string {
  return getTranslation(lang, key);
}

// Batch translation function for multiple keys
export function batchTranslate(lang: Language, keys: string[]): Record<string, string> {
  const result: Record<string, string> = {};
  keys.forEach((key) => {
    result[key] = getTranslation(lang, key);
  });
  return result;
}
