// Helper function to get complete translation
export function getCompleteTranslation(lang: string, key: string): string {
  const keys = key.split('.');
  let value: any = completeTranslations[lang as keyof typeof completeTranslations];

  for (const k of keys) {
    value = value?.[k];
  }

  // Fallback to English
  if (!value) {
    let enValue: any = completeTranslations.en;
    for (const k of keys) {
      enValue = enValue?.[k];
    }
    return enValue || key;
  }

  return value || key;
}
